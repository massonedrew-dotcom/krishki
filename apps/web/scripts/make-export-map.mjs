// Builds the dot grid of the export map from Natural Earth admin-0 outlines (public domain).
//   node apps/web/scripts/make-export-map.mjs prototypes/light-home/tools/data/ne_50m_admin_0_countries.geojson
// Writes src/components/blocks/export-map-data.ts: one SVG path per dot class, so only numbers ship.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = process.argv[2];
if (!src) {
  console.error("usage: node make-export-map.mjs <ne_50m_admin_0_countries.geojson>");
  process.exit(1);
}

const LON0 = 20;
const LON1 = 92;
const LAT0 = 34;
const LAT1 = 60;
const STEP = 0.42; // degrees of latitude per row
const CELL = 10; // SVG units per cell
const kx = Math.cos((((LAT0 + LAT1) / 2) * Math.PI) / 180);
const COLS = Math.round(((LON1 - LON0) * kx) / STEP);
const ROWS = Math.round((LAT1 - LAT0) / STEP);

const DELIVERY = new Set(["KAZ", "KGZ", "TJK", "TKM", "RUS", "BLR", "AZE"]);
// label anchors: a point inside each country, not a claim about a delivery address
const POINTS = {
  kokand: [70.94, 40.53],
  kz: [68, 49],
  kg: [75, 41.6],
  tj: [70.5, 38.6],
  tm: [58.5, 39],
  ru: [42, 55.5],
  by: [28, 53.5],
  az: [48.5, 40.3],
};

const polys = [];
for (const f of JSON.parse(readFileSync(src, "utf8")).features) {
  const g = f.geometry;
  if (!g) continue;
  const list = g.type === "Polygon" ? [g.coordinates] : g.type === "MultiPolygon" ? g.coordinates : [];
  for (const rings of list) {
    const xs = rings[0].map((p) => p[0]);
    const ys = rings[0].map((p) => p[1]);
    const box = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)];
    if (box[1] < LON0 || box[0] > LON1 || box[3] < LAT0 || box[2] > LAT1) continue;
    polys.push({ id: f.properties.ADM0_A3, rings, box });
  }
}

function inRing(x, y, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

function countryAt(lon, lat) {
  for (const p of polys) {
    if (lon < p.box[0] || lon > p.box[1] || lat < p.box[2] || lat > p.box[3]) continue;
    if (inRing(lon, lat, p.rings[0]) && !p.rings.slice(1).some((r) => inRing(lon, lat, r))) return p.id;
  }
  return null;
}

const paths = { home: "", delivery: "", other: "" };
for (let r = 0; r < ROWS; r++) {
  for (let c = 0; c < COLS; c++) {
    const col = c + (r % 2 ? 0.5 : 0) + 0.5;
    const id = countryAt(LON0 + (col * STEP) / kx, LAT1 - (r + 0.5) * STEP);
    if (!id) continue;
    const kind = id === "UZB" ? "home" : DELIVERY.has(id) ? "delivery" : "other";
    paths[kind] += `M${col * CELL} ${(r + 0.5) * CELL}h0`;
  }
}

const points = Object.fromEntries(
  Object.entries(POINTS).map(([k, [lon, lat]]) => [
    k,
    [Math.round((((lon - LON0) * kx) / STEP) * CELL), Math.round(((LAT1 - lat) / STEP) * CELL)],
  ]),
);

const out = `// Generated by scripts/make-export-map.mjs from Natural Earth (public domain). Do not edit by hand.
export const MAP_W = ${COLS * CELL};
export const MAP_H = ${ROWS * CELL};
export const DOTS = ${JSON.stringify(paths)} as const;
export const POINTS = ${JSON.stringify(points)} as const;
`;
writeFileSync(resolve(here, "../src/components/blocks/export-map-data.ts"), out);
console.log(`grid ${COLS}x${ROWS}, ${out.length} chars`, points);
